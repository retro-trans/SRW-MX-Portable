def footer(boot, names, costs, npc=False, unknown=False):
    u = previous.machine(boot)
    obj, row, ctx, strings = 0x1000000, 0x1010000, 0x1020000, 0x1030000
    u.mem_write(row+0xb0, struct.pack('<h', 1))
    u.mem_write(row+0xcc, struct.pack('<hh', 98, 98))
    u.mem_write(row+0x18, bytes([8 if npc else 0]))
    u.mem_write(ctx+8, struct.pack('<ff', 14, 14))
    for n, (name, cost) in enumerate(zip(names, costs)):
        ptr = strings+n*256
        u.mem_write(ptr, it.encode(name))
        u.mem_write(row+0x6c+n*4, struct.pack('<I', 0 if unknown else ptr))
        u.mem_write(row+0xde+n*2, struct.pack('<h', cost))
    draws = []
    def callbacks(u, pc, size, _):
        if pc in (0xaeb08, 0xaf548):
            a0, a1, x, y = [u.reg_read(r) for r in [UC_MIPS_REG_A0, UC_MIPS_REG_A1, UC_MIPS_REG_A2, UC_MIPS_REG_A3]]
            raw = previous.cstr(u, a1)
            font = struct.unpack('<f', u.mem_read(a0+8, 4))[0]
            draws.append(dict(renderer=hex(pc), raw=raw.hex(), text=raw.decode('cp932'), x=x, y=y, font=font))
        elif pc == 0xb0368:  # color/style only; keep native dimensions set by caller
            pass
        elif pc == 0x259020:
            dest, fmt, a2, a3 = [u.reg_read(r) for r in [UC_MIPS_REG_A0, UC_MIPS_REG_A1, UC_MIPS_REG_A2, UC_MIPS_REG_A3]]
            text = previous.cstr(u, fmt).decode('ascii') % ((a2, a3) if b'/' in previous.cstr(u, fmt) else a2)
            u.mem_write(dest, text.encode('ascii')+b'\0')
        else:
            return
        u.reg_write(UC_MIPS_REG_PC, u.reg_read(UC_MIPS_REG_RA))
    u.hook_add(UC_HOOK_CODE, callbacks)
    u.reg_write(UC_MIPS_REG_T0, 0)
    previous.invoke(u, 0x21a844, [obj, row, ctx, 0])
    # Measure with the same two native width functions used by the renderers.
    for draw in draws:
        u.mem_write(strings+0x1000, bytes.fromhex(draw['raw'])+b'\0')
        u.mem_write(ctx+8, struct.pack('<ff', draw['font'], 14))
        previous.invoke(u, 0xb03e4 if draw['renderer']=='0xaeb08' else 0xb04d8, [ctx, strings+0x1000])
        draw['width'] = u.reg_read(UC_MIPS_REG_V0)
        draw['right'] = draw['x']+draw['width']
    return draws


def check_footer(draws):
    for slot in range(6):
        x, y = 132+(slot%3)*102, 8+(slot//3)*18
        items = [d for d in draws if d['y'] in (y,y+1) and x-8 <= d['x'] < x+94]
        assert len(items)==4, (slot, items)
        ordered=sorted(items,key=lambda d:d['x'])
        assert all(a['right'] <= b['x'] for a,b in zip(ordered,ordered[1:])), ordered
        assert ordered[-1]['right'] <= x+94, ordered
    return True


def level_up_draw(boot):
    draws = []
    def capture(u, obj):
        ctx, strings = obj+0x1a8, 0x10e0000
        u.mem_write(strings, it.encode('Judau'))
        u.mem_write(obj+0x200, struct.pack('<III', strings, 14, 19))
        u.mem_write(obj+0xa0, bytes(8))
        u.mem_write(obj+0x20c, struct.pack('<6i', *([-1]*6)))
        # Preserve all six pointers generated by the real formatter.
        u.mem_write(obj+0x23c, struct.pack('<6i', *([2]*6)))
        u.mem_write(obj+0x254, struct.pack('<6i', *([1]*6)))
        u.mem_write(obj+0x284, struct.pack('<6i', *([2]*6)))
        def callback(u, pc, size, _):
            if pc in (0x201778,0x201d2c,0x201d24,0x201808,0x1afed8,0xb0368):
                pass
            elif pc in (0xaeb08,0xaf548):
                a0,a1,x,y=[u.reg_read(r) for r in [UC_MIPS_REG_A0,UC_MIPS_REG_A1,UC_MIPS_REG_A2,UC_MIPS_REG_A3]]
                draws.append(dict(renderer=hex(pc),raw=previous.cstr(u,a1).hex(),x=x,y=y,
                                  font=struct.unpack('<f',u.mem_read(a0+8,4))[0]))
            elif pc==0x259020:
                dest,fmt,value=[u.reg_read(r) for r in [UC_MIPS_REG_A0,UC_MIPS_REG_A1,UC_MIPS_REG_A2]]
                text=previous.cstr(u,fmt).decode('ascii')%value
                u.mem_write(dest,text.encode('ascii')+b'\0')
            else:return
            u.reg_write(UC_MIPS_REG_PC,u.reg_read(UC_MIPS_REG_RA))
        handle=u.hook_add(UC_HOOK_CODE,callback)
        previous.invoke(u,0x1b4d7c,[obj])
        u.hook_del(handle)
        for d in draws:
            u.mem_write(strings+256,bytes.fromhex(d['raw'])+b'\0')
            u.mem_write(ctx+8,struct.pack('<ff',d['font'],14))
            previous.invoke(u,0xb03e4 if d['renderer']=='0xaeb08' else 0xb04d8,[ctx,strings+256])
            d.update(text=bytes.fromhex(d['raw']).decode('cp932'),width=u.reg_read(UC_MIPS_REG_V0))
        for row in range(6):
            items=sorted([d for d in draws if d['y']==67+18*row],key=lambda d:d['x'])
            assert len(items)==3,items
            assert items[0]['x']==130 and items[1]['x']==260 and items[2]['x']==282
            assert all(a['x']+a['width']<=b['x'] for a,b in zip(items,items[1:])),items
            assert items[-1]['x']+items[-1]['width']<=323,items
    result=previous.level_up(boot,True,capture=capture)
    result.update(native_window_draw_verified=True,displayed_rows=draws,
                  battle_playthrough_verified=False)
    return result


def main():
    baseline=read_iso(str(ROOT/'work/output/SRWMX_EN_0.4.12.iso'),
                      ['/PSP_GAME/SYSDIR/BOOT.BIN'])['/PSP_GAME/SYSDIR/BOOT.BIN']
    boot=fix.patch_boot(baseline)
    actual=read_iso(str(ROOT/'work/output/SRWMX_EN_0.4.13.iso'),
                    ['/PSP_GAME/SYSDIR/BOOT.BIN'])['/PSP_GAME/SYSDIR/BOOT.BIN']
    assert actual==boot, 'Verify the built ISO, not only an in-memory patch'
    boot=actual
    sp=json.loads((ROOT/'work/translation/en/static2/spirits.json').read_text())
    report=[]
    sample=['Bless','Focus','Trust','????','Cheer','????']
    costs=[35,15,25,0,70,0]
    old=footer(baseline,sample,costs)
    try:check_footer(old)
    except AssertionError:pass
    else:raise AssertionError('Old footer should reproduce the overlap')
    new=footer(boot,sample,costs);check_footer(new)
    for name in sp.values():
        for cost in (1,70,150):
            draws=footer(boot,[name]*6,[cost]*6);check_footer(draws)
            report.append(dict(name=name,cost=cost,all_six_cells_fit=True))
    for npc,unknown,cost in [(False,False,0),(False,True,50),(True,False,50)]:
        draws=footer(boot,sample,[cost]*6,npc,unknown);check_footer(draws)
        report.append(dict(npc=npc,unknown=unknown,cost=cost,all_six_cells_fit=True))
    level=level_up_draw(boot)
    narration=previous.narration(boot)
    result=dict(version=fix.VERSION,original_footer_collision_reproduced=True,
                native_footer_cases=report,reported_footer_draws=new,
                level_up=level,baseline_0_4_12_level_up=level_up_draw(baseline),
                narration=narration,built_iso_boot_verified=True)
    (ROOT/f'work/output/psp_ui_{fix.VERSION}_execution.json').write_text(json.dumps(result,indent=1))
    print('Footer cases:',len(report),'; Level Up and narration regressions pass.')


if __name__=='__main__':main()
